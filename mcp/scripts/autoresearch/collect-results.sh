#!/usr/bin/env zsh
# Collect completed eval results and write to experiment-log.md + results.tsv
# Run after run-baseline-evals.sh completes.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
LOG="$SCRIPT_DIR/experiment-log.md"
RESULTS_TSV="$SCRIPT_DIR/results.tsv"

# Create results.tsv header if it doesn't exist
if [[ ! -f "$RESULTS_TSV" ]]; then
  echo -e "run\tpass_rate\tmean_dimension\ttotal_mechanical\thypothesis\tkept\tnotes\ttimestamp" > "$RESULTS_TSV"
fi

# Determine next run number
NEXT_RUN=1
if [[ -f "$RESULTS_TSV" ]]; then
  LAST=$(tail -n +2 "$RESULTS_TSV" | tail -1 | cut -f1)
  if [[ -n "$LAST" && "$LAST" =~ ^[0-9]+$ ]]; then
    NEXT_RUN=$((LAST + 1))
  fi
fi

echo "Collecting results..."
echo ""

ARCHS=(null a b c d e f)
declare -A PASS_RATES

for arch in "${ARCHS[@]}"; do
  JSON="/tmp/eval-arch-${arch}.json"
  if [[ ! -f "$JSON" ]]; then
    echo "  [arch-${arch}] NOT FOUND — skipping"
    continue
  fi

  PASS_RATE=$(python3 -c "import json,sys; d=json.load(open('$JSON')); print(d['pass_rate'])" 2>/dev/null || echo "")
  if [[ -z "$PASS_RATE" ]]; then
    echo "  [arch-${arch}] INVALID JSON — skipping"
    continue
  fi

  MEAN_DIM=$(python3 -c "import json; d=json.load(open('$JSON')); print(d['mean_dimension'])" 2>/dev/null || echo "0")
  TOTAL_MECH=$(python3 -c "import json; d=json.load(open('$JSON')); print(d['total_mechanical'])" 2>/dev/null || echo "0")
  WORST=$(python3 -c "import json; d=json.load(open('$JSON')); print(', '.join(d.get('worst_violations', [])[:3]))" 2>/dev/null || echo "")

  PASS_RATES["$arch"]="$PASS_RATE"

  # Append to results.tsv
  HYPOTHESIS="baseline comparison: arch-${arch}"
  echo -e "${NEXT_RUN}\t${PASS_RATE}\t${MEAN_DIM}\t${TOTAL_MECH}\t${HYPOTHESIS}\ttrue\t${WORST}\t$(date -u +%Y-%m-%dT%H:%M:%SZ)" >> "$RESULTS_TSV"
  NEXT_RUN=$((NEXT_RUN + 1))

  echo "  [arch-${arch}] pass_rate=${PASS_RATE}, mean_dim=${MEAN_DIM}, mech=${TOTAL_MECH}"
done

echo ""
echo "Results appended to $RESULTS_TSV"
echo ""

# Write experiment-log.md
cat > "$LOG" << 'LOGEOF'
# Experiment Log

Auto-generated by collect-results.sh. Updated by hand during loop.ts optimization.

## SAM-189 Baseline Architecture Comparison
LOGEOF

echo "" >> "$LOG"
echo "**Date:** $(date -u +%Y-%m-%d)" >> "$LOG"
echo "" >> "$LOG"
echo "### Results" >> "$LOG"
echo "" >> "$LOG"
echo "| Architecture | Pass Rate | Notes |" >> "$LOG"
echo "|---|---|---|" >> "$LOG"

for arch in "${ARCHS[@]}"; do
  RATE="${PASS_RATES[$arch]:-N/A}"
  case "$arch" in
    null) NOTE="Null hypothesis (zero-shot)" ;;
    a)    NOTE="Rules-only baseline" ;;
    b)    NOTE="Exemplars / few-shot" ;;
    c)    NOTE="Two-pass editor" ;;
    d)    NOTE="Corrections-as-context (Lehmann method)" ;;
    e)    NOTE="Hybrid corrections + high-signal rules (leader)" ;;
    f)    NOTE="Aegis governance schema" ;;
    *)    NOTE="" ;;
  esac
  echo "| arch-${arch} | ${RATE} | ${NOTE} |" >> "$LOG"
done

echo "" >> "$LOG"

# Falsification checkpoint
ARCH_E_RATE="${PASS_RATES[e]:-}"
ARCH_NULL_RATE="${PASS_RATES[null]:-}"
ARCH_A_RATE="${PASS_RATES[a]:-}"
ARCH_D_RATE="${PASS_RATES[d]:-}"

echo "## Falsification checkpoint" >> "$LOG"
echo "" >> "$LOG"
echo "Threshold: simpler approach within 5pp of arch-e → thesis challenged." >> "$LOG"
echo "" >> "$LOG"

if [[ -n "$ARCH_E_RATE" && -n "$ARCH_NULL_RATE" ]]; then
  DELTA_NULL=$(python3 -c "print(round(float('$ARCH_E_RATE') - float('$ARCH_NULL_RATE'), 3))" 2>/dev/null || echo "N/A")
  DELTA_A=$(python3 -c "print(round(float('$ARCH_E_RATE') - float('$ARCH_A_RATE'), 3))" 2>/dev/null || echo "N/A")
  DELTA_D=$(python3 -c "print(round(float('$ARCH_E_RATE') - float('$ARCH_D_RATE'), 3))" 2>/dev/null || echo "N/A")

  echo "| Competitor | arch-e rate | competitor rate | delta |" >> "$LOG"
  echo "|---|---|---|---|" >> "$LOG"
  echo "| Null (zero-shot) | ${ARCH_E_RATE} | ${ARCH_NULL_RATE} | +${DELTA_NULL} |" >> "$LOG"
  echo "| arch-a (rules-only) | ${ARCH_E_RATE} | ${ARCH_A_RATE} | +${DELTA_A} |" >> "$LOG"
  echo "| arch-d (corrections-only) | ${ARCH_E_RATE} | ${ARCH_D_RATE} | +${DELTA_D} |" >> "$LOG"
  echo "" >> "$LOG"

  # Determine verdict
  MAX_COMPETITOR=$(python3 -c "
rates = [float(x) for x in ['$ARCH_NULL_RATE','$ARCH_A_RATE','$ARCH_D_RATE'] if x != 'N/A']
if rates: print(max(rates))
else: print(0)
" 2>/dev/null || echo "0")

  VERDICT=$(python3 -c "
e = float('$ARCH_E_RATE')
mc = float('$MAX_COMPETITOR')
delta = e - mc
if delta <= 0.05:
    print('**THESIS CHALLENGED** — simplest competitor within 5pp of arch-e')
else:
    print('**Thesis confirmed** — arch-e leads simplest competitor by +' + str(round(delta, 3)))
" 2>/dev/null || echo "N/A")

  echo "$VERDICT" >> "$LOG"
fi

echo "" >> "$LOG"
echo "## Notes" >> "$LOG"
echo "" >> "$LOG"
echo "- Every.to paired-examples test BLOCKED: only 14/258 corrections have polarity (need ≥20)" >> "$LOG"
echo "- writing_type coverage: 100% (258/258) — type-filtered tests fully unblocked" >> "$LOG"
echo "- 27-sample variance is real — run 2x minimum before drawing conclusions" >> "$LOG"
echo "- Next step: run loop.ts optimization on arch-e (the leader) to find the ceiling" >> "$LOG"

echo "Experiment log written to $LOG"
